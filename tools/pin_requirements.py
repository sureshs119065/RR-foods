#!/usr/bin/env python3
"""Exact version pins (step 5.7).

requirements.txt keeps compatible ranges (what you edit). `requirements.lock` is the exact, reproducible set:
every package the app needs, including indirect ones, as name==version.

    pip install -r requirements.txt && pytest -q     # prove this set works
    python tools/pin_requirements.py                 # write requirements.lock from what is installed
    python tools/pin_requirements.py --check         # fail if the lock is missing, has a non-== line, or no longer
                                                     # satisfies requirements.txt
Deploy with:  pip install -r requirements.lock   (Dockerfile / Render build command)
"""
from __future__ import annotations

import argparse
import re
import sys
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
HEADER = ("# Generated by tools/pin_requirements.py from the installed, tested set. Do not edit by hand.\n"
          "# Update: pip install -U -r requirements.txt && pytest -q && python tools/pin_requirements.py\n")


def read_requirements(path: Path) -> list[Requirement]:
    out = []
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if line and not line.startswith("-"):
            out.append(Requirement(line))
    return out


def resolve(roots: list[Requirement]) -> dict[str, str]:
    """Walks installed metadata from the roots; returns {canonical name: version}."""
    extras_for: dict[str, set[str]] = {}   # every extra requested for each package so far
    done: set[tuple[str, frozenset]] = set()
    queue = [(canonicalize_name(r.name), frozenset(r.extras)) for r in roots]
    while queue:
        name, extras = queue.pop()
        if (name, extras) in done:
            continue
        done.add((name, extras))
        extras_for.setdefault(name, set()).update(extras)
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            raise SystemExit(f"{name} is not installed; run `pip install -r requirements.txt` first")
        envs = [{"extra": ""}] + [{"extra": e} for e in extras]
        for text in dist.requires or []:
            req = Requirement(text)
            if req.marker is None or any(req.marker.evaluate(e) for e in envs):
                queue.append((canonicalize_name(req.name), frozenset(req.extras)))
    return {n: metadata.version(n) for n in sorted(extras_for)}


def write_lock(path: Path, reqs: Path) -> int:
    pins = resolve(read_requirements(reqs))
    path.write_text(HEADER + "".join(f"{n}=={v}\n" for n, v in pins.items()))
    print(f"wrote {path.name}: {len(pins)} packages")
    return 0


def check_lock(path: Path, reqs: Path) -> int:
    if not path.exists():
        print(f"FAIL: {path.name} is missing. Run: python tools/pin_requirements.py")
        return 1
    pinned: dict[str, str] = {}
    bad = []
    for n, raw in enumerate(path.read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.fullmatch(r"([A-Za-z0-9][A-Za-z0-9._-]*)==([A-Za-z0-9][A-Za-z0-9._+!-]*)", line)
        if not m:
            bad.append(f"line {n}: {raw.strip()!r} is not name==version")
        else:
            pinned[canonicalize_name(m.group(1))] = m.group(2)
    for r in read_requirements(reqs):
        v = pinned.get(canonicalize_name(r.name))
        if v is None:
            bad.append(f"{r.name} is in {reqs.name} but not pinned")
        elif not r.specifier.contains(v, prereleases=True):
            bad.append(f"{r.name}=={v} no longer satisfies '{r.specifier}' in {reqs.name}")
    for b in bad:
        print("FAIL:", b)
    if not bad:
        print(f"OK: {len(pinned)} exact pins, all within the ranges in {reqs.name}")
    return 1 if bad else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--requirements", default=str(ROOT / "requirements.txt"))
    ap.add_argument("--lock", default=str(ROOT / "requirements.lock"))
    a = ap.parse_args(argv)
    return (check_lock if a.check else write_lock)(Path(a.lock), Path(a.requirements))


if __name__ == "__main__":
    sys.exit(main())
